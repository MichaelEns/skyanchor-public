import fs from 'node:fs'
import path from 'node:path'
import {createHash} from 'node:crypto'
const walk = dir =>
  fs
    .readdirSync(dir, {withFileTypes: true})
    .flatMap(entry =>
      entry.isDirectory()
        ? walk(path.join(dir, entry.name))
        : [path.join(dir, entry.name)],
    )
const originals = JSON.parse(
  fs.readFileSync(
    path.join('scripts', 'skyanchor', 'original-assets.json'),
    'utf8',
  ),
)
const forbiddenHashes = new Set(originals.map(asset => asset.sha256))
const fragments = originals.flatMap(asset => asset.fragments)
const failures = []
const permittedSourceFiles = originals
  .map(asset => asset.file)
  .filter(file => fs.existsSync(file) && /\.(png|webp|jpe?g|svg)$/.test(file))
  .concat(
    [
      path.join('assets', 'skyanchor'),
      path.join('assets', 'fonts', 'inter'),
      path.join('assets', 'icons', 'flags'),
      path.join(
        'node_modules',
        '@react-navigation',
        'elements',
        'lib',
        'module',
        'assets',
      ),
    ].flatMap(walk),
  )
  .concat([
    path.join('public', 'skyanchor-192.png'),
    path.join('public', 'skyanchor-512.png'),
  ])
const permittedHashes = new Set(
  permittedSourceFiles.map(file =>
    createHash('sha256').update(fs.readFileSync(file)).digest('hex'),
  ),
)
const files = walk('dist').filter(
  file => path.basename(file) !== 'skyanchor-provenance.json',
)
for (const file of files) {
  const bytes = fs.readFileSync(file)
  if (
    /\.(png|webp|jpe?g|svg|ttf|woff2?)$/.test(file) &&
    !permittedHashes.has(createHash('sha256').update(bytes).digest('hex'))
  ) {
    failures.push(
      `${file}: image/font is outside the explicit licensed source hash allowlist`,
    )
  }
  if (forbiddenHashes.has(createHash('sha256').update(bytes).digest('hex')))
    failures.push(`${file}: upstream restricted asset hash`)
  if (/\.(js|html|json|css|svg|map)$/.test(file)) {
    const text = bytes.toString()
    if (fragments.some(fragment => text.includes(fragment)))
      failures.push(`${file}: restricted vector path`)
    for (const pattern of [
      /https:\/\/events\.bsky\.app/,
      /sdk-7gkUkGy9wguUjyFe/,
      /https:\/\/updates\.bsky\.app/,
      /x-atproto-device-id/,
      /x-atproto-session-id/,
      /https:\/\/[^"'\s]+\.ingest\.sentry\.io/,
    ])
      if (pattern.test(text)) failures.push(`${file}: ${pattern}`)
    if (file.endsWith('.map'))
      failures.push(`${file}: source maps must not be shipped`)
  }
}
for (const name of [
  'LICENSE.txt',
  'NOTICE.md',
  'OFL.txt',
  'flags-MIT.txt',
  'APACHE-2.0.txt',
  'lucide-ISC.txt',
  'react-navigation-MIT.txt',
  'tiptap-MIT.txt',
  'zod-MIT.txt',
  'zod-backport.json',
]) {
  if (!fs.existsSync(path.join('dist', 'licenses', name)))
    failures.push(`Missing ${name}`)
}
const report = {
  files: files.length,
  restrictedSourceHashes: forbiddenHashes.size,
  restrictedVectorFragments: fragments.length,
  permittedSourceHashes: permittedHashes.size,
  generatedFavicon:
    'favicon.ico is generated by Expo from the replaced configured source favicon; ICO conversion is not byte-identical to its PNG input',
  failures,
  artifacts: files.map(file => ({
    file,
    sha256: createHash('sha256').update(fs.readFileSync(file)).digest('hex'),
  })),
}
fs.writeFileSync(
  path.join('dist', 'skyanchor-provenance.json'),
  JSON.stringify(report, null, 2) + '\n',
)
console.log(
  `Artifact license/telemetry scan: ${files.length} files, ${failures.length} failures`,
)
if (failures.length) throw new Error(failures.join('\n'))
